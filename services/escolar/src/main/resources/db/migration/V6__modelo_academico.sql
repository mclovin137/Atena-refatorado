    requisito_id bigint NOT NULL REFERENCES requisito_formacao(id),
    materia_id bigint NOT NULL REFERENCES materia(id),
    PRIMARY KEY(requisito_id,materia_id)
);
CREATE INDEX requisito_materia_materia ON requisito_materia(materia_id);
CREATE TABLE aluno (pessoa_id bigint PRIMARY KEY REFERENCES pessoa(id) ON DELETE CASCADE);
CREATE TABLE professor (pessoa_id bigint PRIMARY KEY REFERENCES pessoa(id) ON DELETE CASCADE);
ALTER TABLE matricula ADD CONSTRAINT matricula_subtipo_aluno
    FOREIGN KEY(aluno_id) REFERENCES aluno(pessoa_id) NOT VALID;
ALTER TABLE disciplina ADD CONSTRAINT disciplina_subtipo_professor
    FOREIGN KEY(professor_id) REFERENCES professor(pessoa_id) NOT VALID;
CREATE INDEX disciplina_professor ON disciplina(professor_id);
CREATE TABLE matricula_disciplina (
    matricula_id bigint NOT NULL REFERENCES matricula(id) ON DELETE CASCADE,
    disciplina_id bigint NOT NULL REFERENCES disciplina(id) ON DELETE CASCADE,
    PRIMARY KEY(matricula_id,disciplina_id)
);
CREATE INDEX matricula_disciplina_disciplina ON matricula_disciplina(disciplina_id);

-- O contexto da associação é derivado das duas entidades; nenhum terceiro turma_id duplicado.
CREATE FUNCTION validar_contexto_matricula_disciplina() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM matricula WHERE id=NEW.matricula_id FOR NO KEY UPDATE;
    PERFORM 1 FROM disciplina WHERE id=NEW.disciplina_id FOR NO KEY UPDATE;
    IF NOT EXISTS (
        SELECT 1 FROM matricula m JOIN disciplina d ON d.turma_id=m.turma_id
        WHERE m.id=NEW.matricula_id AND d.id=NEW.disciplina_id
    ) THEN
        RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Associação acadêmica incoerente';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER matricula_disciplina_contexto BEFORE INSERT OR UPDATE ON matricula_disciplina
    FOR EACH ROW EXECUTE FUNCTION validar_contexto_matricula_disciplina();

-- Subtipos são projeções da identidade/perfil existente, mantidas em qualquer caminho de escrita.
CREATE FUNCTION sincronizar_subtipos_pessoa() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.perfil <> 'ALUNO' THEN DELETE FROM aluno WHERE pessoa_id=NEW.id; END IF;
    IF NEW.perfil <> 'PROFESSOR' THEN DELETE FROM professor WHERE pessoa_id=NEW.id; END IF;
    IF NEW.perfil = 'ALUNO' THEN INSERT INTO aluno(pessoa_id) VALUES(NEW.id) ON CONFLICT DO NOTHING; END IF;
    IF NEW.perfil = 'PROFESSOR' THEN INSERT INTO professor(pessoa_id) VALUES(NEW.id) ON CONFLICT DO NOTHING; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER pessoa_subtipos AFTER INSERT OR UPDATE OF perfil ON pessoa
    FOR EACH ROW EXECUTE FUNCTION sincronizar_subtipos_pessoa();

CREATE FUNCTION associar_matricula_ofertas() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO matricula_disciplina(matricula_id,disciplina_id)
        SELECT NEW.id,id FROM disciplina WHERE turma_id=NEW.turma_id ON CONFLICT DO NOTHING;
    RETURN NEW;
END $$;
CREATE TRIGGER matricula_ofertas AFTER INSERT ON matricula
    FOR EACH ROW EXECUTE FUNCTION associar_matricula_ofertas();
CREATE FUNCTION associar_oferta_matriculas() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO matricula_disciplina(matricula_id,disciplina_id)
        SELECT id,NEW.id FROM matricula WHERE turma_id=NEW.turma_id ON CONFLICT DO NOTHING;
    RETURN NEW;
END $$;
CREATE TRIGGER oferta_matriculas AFTER INSERT ON disciplina
    FOR EACH ROW EXECUTE FUNCTION associar_oferta_matriculas();

CREATE FUNCTION impedir_troca_contexto_academico() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.turma_id IS DISTINCT FROM OLD.turma_id THEN
        IF TG_TABLE_NAME = 'matricula' THEN
            IF EXISTS(SELECT 1 FROM matricula_disciplina WHERE matricula_id=NEW.id) THEN
                RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Matrícula possui associações em outra turma';
            END IF;
        ELSIF EXISTS(SELECT 1 FROM matricula_disciplina WHERE disciplina_id=NEW.id) THEN
            RAISE EXCEPTION USING ERRCODE='23514', MESSAGE='Oferta possui associações em outra turma';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER matricula_contexto BEFORE UPDATE OF turma_id ON matricula
    FOR EACH ROW EXECUTE FUNCTION impedir_troca_contexto_academico();
CREATE TRIGGER disciplina_contexto BEFORE UPDATE OF turma_id ON disciplina
    FOR EACH ROW EXECUTE FUNCTION impedir_troca_contexto_academico();

-- Ambas criações serializam o cadastro derivado na mesma turma, sem conflitar com locks de FK.
CREATE FUNCTION serializar_cadastro_turma() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM 1 FROM turma WHERE id=NEW.turma_id FOR NO KEY UPDATE;
    RETURN NEW;
END $$;
CREATE TRIGGER matricula_serializacao BEFORE INSERT ON matricula
    FOR EACH ROW EXECUTE FUNCTION serializar_cadastro_turma();
CREATE TRIGGER disciplina_serializacao BEFORE INSERT ON disciplina
    FOR EACH ROW EXECUTE FUNCTION serializar_cadastro_turma();
